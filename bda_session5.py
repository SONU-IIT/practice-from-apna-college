#SENTIMENT ANANLYSIS -- positive negative and neutral

try:
    from textblob import TextBlob  # type: ignore[import-not-found]
except ImportError:
    from collections import namedtuple

    Sentiment = namedtuple("Sentiment", ["polarity", "subjectivity"])

    class TextBlob:
        def __init__(self, text):
            self.text = text

        @property
        def sentiment(self):
            words = [word.strip(" ,.;!?\"'") for word in self.text.lower().split()]
            positive_words = {
                "great": 1,
                "good": 1,
                "excellent": 1,
                "recommend": 1,
                "fast": 1,
                "happy": 1,
            }
            negative_words = {
                "bad": -1,
                "worst": -1,
                "slow": -1,
                "terrible": -1,
                "negative": -1,
            }

            score = 0
            matches = 0
            for word in words:
                if word in positive_words:
                    score += positive_words[word]
                    matches += 1
                elif word in negative_words:
                    score += negative_words[word]
                    matches += 1

            if matches == 0:
                return Sentiment(0.0, 0.0)

            polarity = max(-1.0, min(1.0, score / matches))
            return Sentiment(polarity, 0.5)

